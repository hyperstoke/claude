# Задача: «Какая следующая буква?»
#
# На вход подаётся одна буква русского алфавита в верхнем регистре.
# Нужно найти следующую за ней букву и вывести её на экран.
# Если введённая буква — последняя в алфавите, вывести:
#   Дальше букв нет
#
# Формат входных данных: одна буква русского алфавита в верхнем регистре.
# Формат выходных данных: одна буква в верхнем регистре или текст
# «Дальше букв нет» (без кавычек).
#
# Примечание: буквы Ё в алфавите нет (значит, между Е и Ж кодов Ё быть не должно).


character = input()
character = ord(character) + 1

if chr(character) <= "Я":
    print(chr(character))
else:
    print("Дальше букв нет")