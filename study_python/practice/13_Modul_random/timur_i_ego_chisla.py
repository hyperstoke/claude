"""
Задача: Тимур и его числа 🌶️

Тимур загадал число от 1 до n (включительно), а Руслан собирается его
отгадать. Каждый раз Руслан называет число Тимуру, а Тимур отвечает ему
одним из трёх способов: "больше", "меньше", "ты отгадал!".

Найдите наименьшее количество попыток, которых гарантированно хватит
Руслану, чтобы угадать число Тимура при любом загаданном числе (то есть
нужна оценка на худший случай при оптимальной стратегии Руслана).

Вход: одно натуральное число n
Выход: одно целое число — наименьшее гарантированно достаточное
количество попыток

Пример:
Вход:
"10"
Вывод:
"4"
"""


def ugadaika(num: int) -> int:
    left = 1
    right = num
    count = 0

    while left <= right:
        count += 1
        mid = (left + right) // 2
        left = mid + 1

    return count


n = int(input())

print(ugadaika(n))