"""
Проект: Числовая угадайка

Мини-проект: собрать целую программу из кусочков раздела —
модуль random, циклы, функции, проверка ввода. Базовое задание разрешает
добавлять свои фичи, эта версия расширена (список ниже).

Что делает программа:
1. печатает приветствие "Добро пожаловать в числовую угадайку.";
2. спрашивает у пользователя нижнюю и верхнюю границы диапазона;
3. загадывает случайное целое число в этих границах (обе включительно);
4. в цикле принимает догадки и подсказывает "больше" / "меньше";
5. при верной догадке поздравляет и сообщает число попыток.

Добавлено сверх базового условия (в базовом — диапазон 1..100 без проверок):
- границы диапазона задаёт пользователь;
- проверка границ: ввод повторяется, пока не введено целое неотрицательное число;
- проверка порядка: обе границы спрашиваются заново, пока не станет left < right;
- проверка каждой догадки: число должно быть целым и лежать в [left, right];
- догадка вне диапазона или не число — запрос повторяется;
- неверный ввод не тратит попытку: счётчик растёт только за принятую догадку;
- подсказки "больше" / "меньше" показывают введённое число.

Пример сессии (границы 1 и 100, загадано 31):
"Добро пожаловать в числовую угадайку."
"Введите границу: 1"     # нижняя граница, ввод пользователя
"Введите границу: 100"   # верхняя граница
"Отгадай число в границе от 1 до 100"
"Введи число: 50"
"Загаданное число меньше 50, попробуйте еще раз"
"Введи число: 25"
"Загаданное число больше 25, попробуйте еще раз"
"Введи число: 37"
"Загаданное число меньше 37, попробуйте еще раз"
"Введи число: 31"
"Вы угадали, поздравляем!"
"Загаданное число 31 за 4 попыток"

Допущения:
- границы целые и неотрицательные: isdecimal отсекает минус и дробную часть;
- цикл догадок завершается только верным числом, весь ввод заранее готовить не нужно.

Стратегия: см. статью "Бинарный поиск" в разделе "Документация".
"""

import random


# num — сырая строка из input(); годна, если это целое число и входит в [left, right]
def is_valid(num: str, left: int, right: int) -> bool:
    return num.isdecimal() and left <= int(num) <= right


# Спрашивает границу, пока не введут целое неотрицательное
# (isdecimal отсекает минус и дробную часть)
def input_bound() -> int:
    while True:
        num = input("Введите границу: ")
        if num.isdecimal():
            return int(num)
        print("А может быть все-таки введем целое положительное число?")


# Как input_bound, но догадка должна ещё попасть в [left, right]
def input_num(left: int, right: int) -> int:
    while True:
        num = input("Введи число: ")
        if is_valid(num, left, right):
            return int(num)
        print(f"А может быть все-таки введем целое число от {left} до {right}?")


print("Добро пожаловать в числовую угадайку.")
# Обе границы читаем заново, пока нижняя не станет меньше верхней
while True:
    left = input_bound()
    right = input_bound()
    if left < right:
        break
    print("Первая граница должна быть меньше второй, попробуй еще раз...")

# randint включает оба конца: загаданное может быть равно left или right
random_num = random.randint(left, right)
print(f"Отгадай число в границе от {left} до {right}")

attempts = 0
# Игровой цикл: подсказываем «больше»/«меньше», пока догадка не совпадёт
while True:
    attempts += 1
    num = input_num(left, right)
    if num < random_num:
        print(f"Загаданное число больше {num}, попробуйте еще раз")
    elif num > random_num:
        print(f"Загаданное число меньше {num}, попробуйте еще раз")
    else:
        print("Вы угадали, поздравляем!")
        print(f"Загаданное число {random_num} за {attempts} раз")
        break