"""
Своя задачка (не со Stepik): интерактивная «угадай число».

Пользователь загадывает число в диапазоне [left, right], программа угадывает
его делением пополам (бинарный поиск): берёт середину, по ответу
«больше» / «меньше» отбрасывает половину, где числа точно нет, и повторяет.
В конце печатает, за сколько попыток вышло.

Для диапазона из N чисел в худшем случае нужно floor(log2(N)) + 1 попыток
(для 1..100 — ровно 7).
"""

left = int(input("Введите от какого числа загадываете: "))
right = int(input("Введите до какого числа загадываете: "))

attempt = 0
while True:
    mid = (left + right) // 2
    attempt += 1
    print(f"Ваше число: {mid}?")
    verification = input("больше / меньше / равно: ")

    if verification == "равно":
        print(f"Вы угадали число {mid} c {attempt} попыток")
        break
    elif verification == "меньше":
        right = mid - 1
    elif verification == "больше":
        left = mid + 1
