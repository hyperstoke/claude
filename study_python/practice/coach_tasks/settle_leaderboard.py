"""
Задача: Устаканить таблицу лидеров
Тема: сортировка пузырьком: флаг обмена и ранний выход  |  Сложность: 6 (сложная)

Легенда: сервис хранит таблицу лидеров — список очков игроков, отсортированный
по УБЫВАНИЮ (первый в списке — лучший). После каждого раунда очки у нескольких
игроков меняются, но обычно чуть-чуть: таблица остаётся почти упорядоченной.
Гонять полную сортировку каждый раунд накладно, поэтому таблицу «доводят»
пузырьком с ранним выходом — как только очередной проход прошёл без единого
обмена, список уже упорядочен и остальные проходы не нужны. Вызывающему коду
надо ещё знать, сдвинулось ли хоть что-нибудь: если нет — перерисовывать
таблицу на клиенте не надо.

Вход:  список целых чисел scores — очки игроков в текущем порядке таблицы.
Выход: функция settle(scores) сортирует список ПО УБЫВАНИЮ на месте (ничего
не пересоздавая) и ВОЗВРАЩАЕТ True, если за всю сортировку был хотя бы один
обмен, иначе False.

Проход — пройти по соседним парам слева направо и поменять местами те, где
левый МЕНЬШЕ правого (сортировка по убыванию). После каждого прохода смотрим
флаг обмена: если за весь проход не было ни одного обмена — останавливаемся,
больше проходов не делаем.

Примеры:
[30, 10, 20]     -> True    # стало [30, 20, 10]
[30, 20, 10]     -> False   # уже по убыванию, ни одного обмена
[10, 20, 30]     -> True    # стало [30, 20, 10]
[50]             -> False   # один игрок, сравнивать не с чем
[]               -> False   # пустая таблица
[15, 15, 15]     -> False   # равные очки, обменов нет
# в примерах показан аргумент и возвращаемое значение; печатать текст не нужно
"""


def settle(scores):

    for placed in range(len(scores) - 1):
        swap = False
        for i in range(len(scores) - 1 - placed):
            if scores[i] > scores[i + 1]:
                scores[i], scores[i + 1] = scores[i + 1], scores[i]
                swap = True
        if not swap:
            break
    return swap



scores = list(map(int, input().split()))

moved = settle(scores)

print(*scores)
print(moved)
