"""
Задача: Проверка времени запуска в конфиге планировщика
Тема: защитная проверка формата строки  |  Сложность: 5 (средняя)

Легенда: планировщик фоновых задач читает конфиг, который правят руками —
админы, а иногда и заказчик. В каждой задаче есть поле run_at: время
запуска в формате HH:MM. Опечатки там — норма жизни: пропущенный ноль,
дефис вместо двоеточия, "24:00" вместо "00:00". Планировщик обязан
отвергнуть кривую строку и написать в лог, какая задача настроена неверно,
а не упасть с ValueError на старте и утащить за собой все остальные задачи.

Вход:  value — строка произвольного содержания (в том числе пустая).
Выход: True, если время записано корректно, иначе False.

Время корректно, когда выполнено всё сразу:
- длина ровно 5 символов;
- символы 1-2 — цифры, и записанное ими число часов от 0 до 23;
- символ 3 — двоеточие;
- символы 4-5 — цифры, и записанное ими число минут от 0 до 59.

Требование: функция не должна падать ни на каком входе — ни на пустой
строке, ни на буквах вместо цифр. Отвергать, а не выбрасывать исключение.

Примеры:
is_valid_run_at("09:05") -> True
is_valid_run_at("00:00") -> True    # полночь — валидное время
is_valid_run_at("23:59") -> True
is_valid_run_at("24:00") -> False   # часов 24 не бывает
is_valid_run_at("09:60") -> False   # минут 60 не бывает
is_valid_run_at("9:05") -> False    # длина 4, ноль потеряли
is_valid_run_at("09-05") -> False   # разделитель не двоеточие
is_valid_run_at("090:5") -> False   # длина 5, но двоеточие не на месте
is_valid_run_at("0a:05") -> False   # буква вместо цифры
is_valid_run_at("") -> False        # пустая строка, падать нельзя

Проверка — тестами, запуск из корня репозитория:
python3 -m pytest study_python/practice/coach_tasks/test_run_at_format_check.py -q
"""


def is_valid_run_at(value: str) -> bool:
    return (len(value) == 5
            and value[:2].isdigit()
            and 0 <= int(value[:2]) <= 23
            and value[2] == ":"
            and value[3:].isdigit()
            and 0 <= int(value[3:]) <= 59
            )