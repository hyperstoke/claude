"""
Задача: Валидация email в форме техподдержки
Тема: методы строк (strip, lower, count, endswith)  |  Сложность: 4 (средняя)

Легенда: бот техподдержки принимает email из формы обращения перед тем,
как сохранить его в базе. Пользователи вставляют email откуда попало —
с лишними пробелами по краям, в разном регистре — и иногда ошибаются
в формате. Нужно проверить и привести к единому виду перед сохранением.

Email считается валидным, если после удаления пробелов по краям:
- в строке ровно один символ "@";
- внутри строки (не по краям) нет пробелов;
- строка оканчивается на один из разрешённых доменов:
  "@mail.ru", "@gmail.com", "@yandex.ru".

Вход:  одна строка через input() — email, возможно с пробелами по краям
и в произвольном регистре.
Выход: если email валиден — напечатать его в нормализованном виде
(без пробелов по краям, в нижнем регистре); иначе — напечатать
"Неверный email".

Примеры:
    "  User@Mail.RU  "
    -> "user@mail.ru"

    "user@@mail.ru"
    -> "Неверный email"   # два "@"

    "user @mail.ru"
    -> "Неверный email"   # пробел внутри строки

    "user@ya.ru"
    -> "Неверный email"   # домен не из разрешённого списка
"""

# твой код здесь


email = input()

email = email.lower()
email = email.strip()

if email.count(" ") or email.count("@") != 1:
    print("Неверный email")
else:
       if email.endswith(("@mail.ru", "@gmail.com", "@yandex.ru")):
              print(email)
       else:
              print("Неверный email")
