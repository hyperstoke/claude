"""
Задача: Один проход планировщика
Тема: пузырёк — флаг обмена и ранний выход  |  Сложность: 5 (средняя)

Легенда: планировщик воркера держит очередь задач, отсортированную по времени
выполнения. Разгребает он её постепенно — за один тик делает ровно один проход
пузырьком, чтобы не блокировать поток надолго. После прохода планировщику надо
знать, был ли смысл в этом тике: если за весь проход ничего не переставилось,
очередь уже отсортирована и следующий тик не нужен.

Вход:  список целых чисел — время выполнения задач в очереди.
Выход: функция bubble_pass(times) делает ОДИН проход пузырьком по списку
(меняет его на месте) и возвращает True, если хотя бы один обмен произошёл,
иначе False.

Один проход — это пройти по соседним парам слева направо и поменять местами
те, где левый больше правого. Ровно один проход, не до полной сортировки.

Требование: флаг один на весь проход. Выходить из цикла раньше времени
нельзя — проход должен дойти до конца списка.

Примеры:
[3, 1, 2]      -> True    # список стал [1, 2, 3], обмены были
[1, 2, 3]      -> False   # уже по возрастанию, ни одного обмена
[2, 1]         -> True    # список стал [1, 2]
[5]            -> False   # нечего сравнивать
[4, 3, 2, 1]   -> True    # список стал [3, 2, 1, 4]: большее уехало в конец
"""


def bubble_pass(times: list[int]) -> bool:
    swapped = False
    for i in range(len(times) - 1):
        if times[i] > times[i + 1]:
            times[i], times[i + 1] = times[i + 1], times[i]
            swapped = True
    return swapped


queue = [int(x) for x in input().split()]

print(bubble_pass(queue))
