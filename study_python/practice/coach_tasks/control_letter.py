"""
Задача: control_letter (контрольная буква для кода товара)
Тема: таблица Unicode ord/chr — буква ↔ позиция в алфавите  |  Сложность: 2

Легенда: в бэкенде склада каждому товару присваивают короткий буквенный
артикул. Чтобы ловить опечатки при ручном вводе, к артикулу добавляют одну
контрольную букву — она вычисляется из самого артикула. Если оператор
ошибётся в букве, контрольная не сойдётся, и система отклонит код. Такой же
приём (контрольный символ) используют в номерах банковских карт и ISBN.

Как считается контрольная буква:
  1. Позиция буквы в алфавите: a → 0, b → 1, ..., z → 25.
  2. Сложить позиции всех букв артикула.
  3. Взять остаток суммы от деления на 26.
  4. Перевести этот остаток обратно в букву (0 → a, 1 → b, ..., 25 → z) —
     это и есть контрольная буква.

Вход:  одна строка — артикул из строчных латинских букв (без пробелов).
Выход: одна строчная латинская буква — контрольная.

Примеры:
    "abc" -> "d"    # позиции 0+1+2 = 3;  3 % 26 = 3  -> 'd'
    "a"   -> "a"    # позиция 0;          0 % 26 = 0  -> 'a'
    "zzz" -> "x"    # позиции 25*3 = 75;  75 % 26 = 23 -> 'x'
    "abz" -> "a"    # 0+1+25 = 26;        26 % 26 = 0  -> 'a'
"""

# твой код здесь

text = input()
pos_letter = 0

for letter in text:
    pos_letter += ord(letter) - ord("a")

output_letter = pos_letter % 26

print(chr(ord("a") + output_letter))
