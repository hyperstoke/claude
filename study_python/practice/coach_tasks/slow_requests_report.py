"""
Задача: Отчёт по медленным запросам
Тема: списочное выражение (список vs генератор), обход по элементам
Сложность: 4 (средняя)

Легенда: сервис пишет в лог время ответа каждого запроса к API в
миллисекундах. Дежурный инженер раз в час снимает срез и должен понять,
сколько запросов вышло за SLA (300 мс) и какие именно это были значения.
Такой отчёт — типовая задача мониторинга: сначала счётчик для алерта,
потом сами значения для разбора.

Вход:
    одна строка — времена ответа в миллисекундах, целые числа через пробел

Выход:
    первая строка — количество запросов, у которых время >= 300
    далее — сами эти значения, каждое на отдельной строке, в исходном порядке

Требования (в них суть задачи):
    - список медленных времён построить списочным выражением
    - количество получить функцией len() от этого списка
    - значения вывести циклом for

Примеры:
"120 450 300 90 780"    # вход
"3"                     # столько запросов вышли за SLA (300 входит: >= )
"450"
"300"
"780"

"50 100 299"            # вход: медленных нет
"0"                     # счётчик выводится всегда, дальше пусто
"""

response_times = map(int, input().split())

slow_responses = [response for response in response_times if response >= 300]

print(len(slow_responses))

for response in slow_responses:
    print(response)