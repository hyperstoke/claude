"""
Задача: Первая ошибка в логе выкатки
Тема: флаг-паттерн, ветвление, покрывающее все случаи  |  Сложность: 5 (средняя)

Легенда: после выкатки релиза дежурный смотрит лог сервиса и должен быстро
понять, где всё сломалось в первый раз — дальше ошибки обычно сыплются
лавиной, и разбираться надо именно с первой. Если ошибок нет, дежурный
должен увидеть это явным сообщением, а не пустой вывод: молчание программы
неотличимо от того, что она не отработала.

Вход:
    первая строка — число n, количество строк лога
    далее n строк вида "<УРОВЕНЬ> <текст сообщения>", уровень — INFO, WARN
    или ERROR

    n — сколько строк лога есть всего, а не сколько программа обязана
    прочитать. input() читает одну строку в момент вызова, поэтому решение с
    ранним выходом завершится сразу после первой ошибки, и оставшиеся строки
    вводить не нужно: непрочитанный ввод просто отбрасывается. Проверяется
    только то, что программа напечатала.

Выход:
    если ошибка есть — две строки: номер первой строки с уровнем ERROR
    (нумерация с 1, считаются все строки лога) и её текст сообщения без
    уровня
    если ошибок нет — одна строка: "ошибок нет"

Требования (в них суть задачи):
    - после первой найденной ошибки цикл не должен продолжать работу
    - случай «ошибок не было вообще» обязан обрабатываться явно

Примеры:
"4"                          # вход
"INFO service started"
"WARN slow response"
"ERROR db connection lost"
"ERROR timeout"                # эту строку решение с ранним выходом не прочитает
"3"                          # первая ошибка — третья строка лога
"db connection lost"

"2"                          # вход: ошибок нет
"INFO deploy finished"
"WARN cache is cold"
"ошибок нет"

"1"                          # вход: ошибка в самой первой строке
"ERROR bad config"
"1"
"bad config"
"""
count_logs = int(input())
logs = [input() for _ in range(count_logs)]
line = 1

for log in logs:
    if log.startswith("ERROR"):
        print(line, log[log.find(" ") + 1:], sep="\n")
        break
    line += 1
else:
    print("ошибок нет")
