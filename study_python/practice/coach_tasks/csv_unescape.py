"""
Задача: «Разэкранирование CSV-поля»
Тема: разбор строки вручную — обход с индексом, срез подстроки, chr  |  Сложность: 6 (сложная)

Легенда: сервис выгружает данные в CSV. Внутри одного поля не могут
встречаться служебные символы (запятая, пробел, перенос строки) — иначе
они разорвут строку файла. Поэтому при экспорте такие символы ЭКРАНИРУЮТ:
заменяют на конструкцию {NNN}, где NNN — трёхзначный десятичный код
символа в таблице Unicode. Твоя задача на импорте — восстановить
исходный текст поля обратно.

Как устроено экранирование:
  - служебный символ заменён на ровно 5 символов: '{', три цифры, '}';
  - три цифры — код символа с ведущими нулями:
    пробел (код 32) -> {032}, запятая (код 44) -> {044};
  - обычные символы (буквы, цифры) остаются как есть.

Вход:  одна строка — экранированное значение поля.
Выход: одна строка — восстановленный текст поля. Если экранировать нечего,
строка выводится как есть (никаких доп. сообщений печатать не нужно).

Примеры (в кавычках — вход и ожидаемый вывод; после # — пояснение):
    "abc"                  -> "abc"           # экранировать нечего: вывод = ввод
    "Ivanov{044}{032}Ivan" -> "Ivanov, Ivan"  # 044 = ',', 032 = ' '
    "a{033}b"              -> "a!b"           # 033 = '!'
    "{036}100"             -> "$100"          # 036 = '$'
    ""                     -> ""              # пустой вход -> пустой вывод
"""

# твой код здесь

text = input()
i = 0
correct_output = ""

while i < len(text):
    if text[i] == "{":
        correct_output += chr(int(text[i+1:i+4]))
        i += 5
    else:
        correct_output += text[i]
        i += 1

print(correct_output)