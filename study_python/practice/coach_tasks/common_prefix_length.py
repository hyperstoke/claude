"""
Задача: Общий префикс двух строк
Тема: индексация строк вручную, границы while-цикла (off-by-one)  |  Сложность: 4 (средняя)

Легенда: в поиске с автодополнением бэкенд хранит предыдущий введённый
запрос и должен быстро понять, сколько символов совпадает с ним от начала
у нового запроса — если совпадение длинное, можно переиспользовать
закешированные результаты вместо нового обращения к базе.

Как считается: сравнить строки посимвольно от начала. Длина общего
префикса — число подряд идущих одинаковых символов до первого
несовпадения ИЛИ до конца более короткой строки — смотря что наступит
раньше.

Вход:  2 строки, каждая на отдельной строке.
Выход: одно целое число — длина общего префикса.

Примеры:
    "kitten"
    "kits"
    -> 3

    "ab"
    "abc"
    -> 2   # более короткая строка совпала полностью — не выйти за её границу

    ""
    "abc"
    -> 0   # пустая строка на входе
"""

# твой код здесь

word_one = input()
word_two = input()

i = 0
word_overlap = ""

while i <= min(len(word_one), len(word_two)) - 1:
    if word_one[i] == word_two[i]:
        word_overlap += word_one[i]
        i += 1
    else:
        break

print(len(word_overlap))
