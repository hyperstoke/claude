"""
Задача: normalize_slug
Тема: методы строк (lower, replace, strip) + цикл while + in  |  Сложность: 2

Легенда: в CMS блога заголовок статьи приходит от автора как обычный текст
("Как выучить Python за 30 дней"). Перед сохранением в базу и использованием
в URL (/articles/<slug>) его нужно превратить в чистый slug: нижний регистр,
слова через один дефис, без лишних пробелов.

Вход:  строка-заголовок через input() (может быть с лишними пробелами по
краям и между словами, в любом регистре).
Выход: print строки-slug: нижний регистр, пробелы заменены на дефисы,
несколько дефисов/пробелов подряд схлопнуты в один дефис, без
пробелов по краям.

Примеры:
    "Как выучить Python за 30 дней" -> "как-выучить-python-за-30-дней"
    "  Hello   World  "             -> "hello-world"
    "Already-Slugged"               -> "already-slugged"
    ""                               -> ""
"""

title = input()
title = title.strip()
title = title.lower()
title = title.replace(" ", "-")
print(title)
