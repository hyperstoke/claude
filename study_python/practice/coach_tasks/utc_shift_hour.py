"""
Задача: Во сколько сработает задача по расписанию
Тема: нормализация по кругу через остаток  |  Сложность: 3 (средняя)

Легенда: планировщик на бэкенде хранит время запуска задач в UTC, но в админке
время показывают пользователю в его часовом поясе. Сдвиг может быть
отрицательным (UTC-8, Лос-Анджелес) и по модулю больше суток — например, когда
тем же кодом считают «а что было 48 часов назад» при разборе инцидента.
Нужна функция, которая по часу UTC и сдвигу возвращает час на циферблате.

Вход:  hour — целое от 0 до 23, час запуска по UTC;
offset — целое, сдвиг в часах, может быть отрицательным и по модулю > 24.
Выход: целое от 0 до 23 — час после сдвига.

Требование: без ветвлений (if/elif). Одно выражение в return.

Примеры:
get_local_hour(23, 3) -> 2      # перевалили через полночь вперёд
get_local_hour(1, -3) -> 22     # ушли назад за полночь
get_local_hour(23, 26) -> 1     # сдвиг больше суток: 26 ч = сутки + 2 ч
get_local_hour(0, -1) -> 23     # полночь минус час
get_local_hour(10, 0) -> 10     # нулевой сдвиг ничего не меняет
get_local_hour(5, -48) -> 5     # ровно двое суток назад — тот же час
"""


def get_local_hour(hour: int, offset: int) -> int:
    return (hour + offset) % 24


h = int(input())
off = int(input())


print(get_local_hour(h, off))
