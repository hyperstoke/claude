"""
Задача: Проверка артикула на складе
Тема: защитная проверка формата строки  |  Сложность: 5 (средняя)

Легенда: склад принимает артикулы товаров из внешней системы партнёра. Данные
приходят грязные: обрезанные строки, пустые значения, буквы вместо цифр. Если
проверка формата написана небрежно, сервис падает с ValueError или IndexError
прямо на обработке партии — поэтому функция обязана возвращать False на любом
мусоре, а не выбрасывать исключение.

Вход:  code — строка произвольного содержания (в том числе пустая).
Выход: True, если артикул корректен, иначе False.

Артикул корректен, когда выполнено всё сразу:
- длина ровно 7 символов;
- символы 1-2 — заглавные буквы;
- символ 3 — дефис;
- символы 4-7 — цифры, и записанное ими число больше нуля.

Требование: функция не должна падать ни на каком входе. Проверить это руками
на всех примерах ниже, а не только на корректном.

Примеры:
is_valid_sku("AB-1234") -> True
is_valid_sku("ab-1234") -> False   # буквы не заглавные
is_valid_sku("AB-0000") -> False   # число должно быть больше нуля
is_valid_sku("A-B1234") -> False   # длина 7, но дефис не на третьей позиции
is_valid_sku("AB1234") -> False    # длина 6, дефиса нет
is_valid_sku("AB-12345") -> False  # длина 8
is_valid_sku("AB-12a4") -> False   # в номере буква
is_valid_sku("") -> False          # пустая строка, падать нельзя
"""


def is_valid_sku(code: str) -> bool:
    return (len(code) == 7
            and code[:2].isupper() and code[:2].isalpha()
            and code[2] == "-"
            and code[3:].isdigit() and int(code[3:]) > 0)


sku = input()


print(is_valid_sku(sku))