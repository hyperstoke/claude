"""
Задача: Времена ответа — сортировка вручную
Тема: списки, вложенные циклы, обмен элементов, флаг обмена  |  Сложность: 6 (сложная)

Легенда: на скрининге в крупную компанию просят отсортировать данные
вручную — .sort() и sorted() использовать нельзя. Данные настоящие:
времена ответа эндпоинта в миллисекундах за последние минуты. Кроме
самого отсортированного списка от тебя хотят число проходов: по нему
видно, знаешь ли ты, что пузырёк умеет останавливаться раньше, если
список уже отсортирован.

Вход:
одна строка — целые времена ответа в мс через пробел (чисел хотя бы одно)

Выход:
две строки —
первая: те же числа по возрастанию, через пробел
вторая: "Проходов: N"

Правила:
- .sort(), sorted(), min(), max() не использовать — сортировать самому
- проход = один проход внешнего цикла по списку
- если за проход не случилось ни одного обмена, список уже отсортирован:
дальше не идти, но сам этот проход посчитать

Примеры:

вход:  "5 1 4 2 8"
выход: "1 2 4 5 8" и "Проходов: 3"   # 2 прохода с обменами + 1 контрольный, без обменов

вход:  "10 20 30"
выход: "10 20 30" и "Проходов: 1"   # уже отсортировано, обменов не было — выходим сразу

вход:  "3 2 1"
выход: "1 2 3" и "Проходов: 3"   # худший случай для трёх элементов

вход:  "42"
выход: "42" и "Проходов: 1"   # одно число: сравнивать не с чем, обменов нет
"""

timings = list(map(int, input().split()))
passes = 0

for i in range(len(timings)):
    swapped = False
    passes += 1

    for j in range(len(timings) - i - 1):
        if timings[j] > timings[j + 1]:
            timings[j], timings[j + 1] = timings[j + 1], timings[j]
            swapped = True

    if not swapped:
        break

print(*timings)
print(f"Проходов: {passes}")