"""
Задача: Проверка пароля при регистрации
Тема: флаг-паттерн для нескольких независимых условий  |  Сложность: 5 (средняя)

Легенда: сервис регистрации проверяет пароль на бэкенде (даже если фронт уже
проверил на JS — доверять клиенту нельзя). Нужно пройти по паролю
посимвольно и одновременно отследить несколько независимых требований, не
путая «дошли до конца строки» с «пароль подходит».

Вход:  одна строка — пароль. 
Выход: "OK", если пароль содержит хотя бы одну цифру, хотя бы одну заглавную
букву и не содержит ни одного пробела. Иначе — "Слабый пароль".
Если в пароле встретился пробел — прекратить посимвольный разбор сразу
(дальше можно не смотреть), но итоговый вердикт всё равно "Слабый пароль".

Примеры:
    "Qwerty1"
    -> "OK"

    "qwerty1"
    -> "Слабый пароль"   # нет заглавной буквы

    "Qwerty"
    -> "Слабый пароль"   # нет цифры

    "Qwe rty1"
    -> "Слабый пароль"   # есть пробел, разбор прерван на нём
"""

# твой код здесь

password = input()

upper_letter = any(symb.isupper() for symb in password)
has_digital = any(symb.isdigit() for symb in password)
spaces = " " in password

if not spaces and upper_letter and has_digital:
    print("OK")
else:
    print("Слабый пароль")