"""
Задача: Досортировать топ поисковых подсказок
Тема: сортировка пузырьком: флаг обмена и ранний выход  |  Сложность: 6 (сложная)

Легенда: сервис держит в памяти топ поисковых подсказок — список счётчиков
обращений, отсортированный по УБЫВАНИЮ (первый элемент — самая популярная
подсказка). Раз в минуту счётчики обновляются, но обычно чуть-чуть: список
остаётся почти упорядоченным. Гонять полную сортировку каждую минуту дорого,
поэтому список «доводят» пузырьком с ранним выходом. Вызывающему коду нужно
знать ещё одну вещь: сдвинулось ли хоть что-нибудь. Если нет — подсказки
у клиентов не перерисовывают и кэш не сбрасывают.

Вход:  hits — список целых чисел, счётчики обращений в текущем порядке.
Выход: функция resettle_suggestions(hits) сортирует список ПО УБЫВАНИЮ
на месте (не создавая новый список) и ВОЗВРАЩАЕТ True, если за всю
сортировку был хотя бы один обмен, иначе False.

Проход — пройти по соседним парам слева направо и поменять местами те, где
левый МЕНЬШЕ правого (список по убыванию). После каждого прохода смотрим,
были ли обмены в этом проходе: если ни одного — список уже упорядочен,
оставшиеся проходы не нужны, выходим.

Два разных вопроса — не путать:
"были ли обмены в ЭТОМ проходе" решает, делать ли следующий проход;
"был ли обмен ХОТЯ БЫ РАЗ за всю сортировку" — это то, что возвращает функция.

Примеры:
[30, 10, 20]  -> True   # стало [30, 20, 10]
[30, 20, 10]  -> False  # уже по убыванию, ни одного обмена
[10, 20, 30]  -> True   # стало [30, 20, 10]
[50]          -> False  # один элемент, сравнивать не с чем
[]            -> False  # пустой список, падать нельзя
[15, 15, 15]  -> False  # равные счётчики, обменов нет

Проверка — тестами, запуск из корня репозитория:
python3 -m pytest study_python/practice/coach_tasks/test_resettle_suggestions.py -q
"""


def resettle_suggestions(hits: list) -> bool:
    length = len(hits)
    swapped_any = False
    for i in range(length - 1):
        swapped = False
        for j in range(length - 1 - i):
            if hits[j] < hits[j + 1]:
                hits[j + 1], hits[j] = hits[j], hits[j + 1]
                swapped = True
                swapped_any = True
        if not swapped:
            break
    return swapped_any




