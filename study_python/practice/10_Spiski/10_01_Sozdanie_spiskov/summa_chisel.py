"""
Сумма чисел

На вход программе подаётся строка текста, содержащая натуральные числа.
Напишите программу, которая вставляет между каждым числом знак +, а затем
вычисляет сумму полученных чисел.

Формат входных данных: строка натуральных чисел, разделённых пробелом.
Формат выходных данных: выражение со знаками + и его значение.

Пример входа:
"1 2 3 4 5"

Пример выхода:
"1+2+3+4+5=15"   # точный вид строки (пробелы вокруг = и +) — сверить
# с примером на Stepik, условие его не задаёт
"""

numbers = input().split()
print("+".join(numbers), f"={sum(map(int, numbers))}", sep="")

