"""
Валидный номер (🌶️)

На вход программе подаётся строка текста. Напишите программу, которая
определяет, является ли введённая строка корректным телефонным номером.
Строка является корректным телефонным номером, если она соответствует одному
из форматов:

abc-def-hijk
7-abc-def-hijk

где a, b, c, d, e, f, h, i, j, k — цифры от 0 до 9.

Формат входных данных: строка текста.
Формат выходных данных: "YES", если строка — корректный номер, иначе "NO".

Примечание: номер должен содержать только цифры и символ "-", а количество
цифр в каждой группе должно быть правильным.

Примеры входа и выхода:

"123-456-7890"    -> "YES"
"7-123-456-7890"  -> "YES"
"123-456-789"     -> "NO"    # в последней группе 3 цифры вместо 4
"8-123-456-7890"  -> "NO"    # первая группа есть, но это не 7
"12a-456-7890"    -> "NO"    # не цифра
"""

number = input().split("-")
valid = False

if len(number) == 3 and all(element.isdigit() for element in number):
    if [len(element) for element in number] == [3, 3, 4]:
        valid = True

elif len(number) == 4 and all(element.isdigit() for element in number):
    if number[0] == "7" and [len(element) for element in number[1:]] == [3, 3, 4]:
        valid = True

if valid:
    print("YES")
else:
    print("NO")