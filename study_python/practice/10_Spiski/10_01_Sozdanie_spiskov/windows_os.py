"""
Задача: «Windows OS»

В операционной системе Windows полное имя файла состоит из буквы диска,
после которого ставится двоеточие и символ \, затем через такой же символ
перечисляются подкаталоги (папки), в которых находится файл, в конце
пишется имя файла: "C:\Windows\System32\calc.exe"

На вход программе подаётся одна строка с корректным именем файла в
операционной системе Windows. Напишите программу, которая разбирает строку
на части, разделённые символом \. Каждую часть вывести в отдельной строке.

Формат входных данных:
    Одна строка — полное имя файла.

Формат выходных данных:
    Программа должна вывести текст в соответствии с условием задачи.

Примечание. В Python символ \ используется для специальных
последовательностей (\n — новая строка, \t — табуляция). Если он нужен как
часть строки, его экранируют — пишут два обратных слэша: "\\"

Докстринг этого файла помечен префиксом r (raw), поэтому обратные слэши
внутри него читаются буквально и экранировать их не требуется.
"""

print(*(input().split("\\")), sep="\n")