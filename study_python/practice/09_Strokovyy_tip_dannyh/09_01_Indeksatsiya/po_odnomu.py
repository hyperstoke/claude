# Stepik 9.1 — "По одному"
# Дано: строка из эмодзи-символов — очередь животных на борт самолёта.
# Нужно: для каждого животного вывести его номер в очереди (с 1) и эмодзи
# в формате "<номер>) <эмодзи>"
# Пример: "🦁🦓🐧🦒" ->
# 1) 🦁
# 2) 🦓
# 3) 🐧
# 4) 🦒

emoji = input()

for index, emoji in enumerate(emoji, start = 1):
    print(f"{index}) {emoji}")

