# Задача: соотнести символы с их кодами в таблице Unicode (ASCII).
# Символы: a, A, z, Z, 6, 7
# Коды:    97, 90, 54, 55, 122, 65
# Подсказка из условия: код символа можно узнать функцией ord().
#
# Шпаргалка по блокам ASCII (идут по порядку, запоминать все коды не надо):
#   цифры '0'-'9'   -> 48-57
#   заглавные A-Z   -> 65-90
#   строчные a-z    -> 97-122
# Разница между строчной и заглавной одной буквы всегда 32.

# Проверь себя — выведи коды и сверь со своими ответами:
for symbol in "aAzZ67":
    print(symbol, ord(symbol))
