"""
Задача: «Строковые минимум и максимум»

На вход подаётся последовательность строк, каждая на отдельной строке.
Концом последовательности является слово "КОНЕЦ" (без кавычек) — само оно
в последовательность не входит, лишь сигнализирует об окончании. Нужно
найти в последовательности минимальную и максимальную строки (в
лексикографическом порядке) и вывести их в заданном формате.

Формат входных данных:
    последовательность строк, каждая на отдельной строке; заканчивается
    словом "КОНЕЦ".

Формат выходных данных:
    Минимальная строка ⬇️: <минимальная строка>
    Максимальная строка ⬆️: <максимальная строка>

Примечание: не только у чисел мы можем находить максимум и минимум.
"""

words = []

while True:
    word = input()
    if word == "КОНЕЦ":
        break
    words.append(word)

print(f"Минимальная строка ⬇️: {min(words)}")
print(f"Максимальная строка ⬆️: {max(words)}")