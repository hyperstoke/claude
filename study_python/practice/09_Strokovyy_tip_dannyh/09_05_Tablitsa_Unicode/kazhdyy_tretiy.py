"""
Задача: «Каждый третий»

На вход программе подаётся строка текста. Нужно удалить из неё все
символы с индексами, кратными 3 (индексы 0, 3, 6, 9, ...), и вывести
получившуюся строку.

Формат входных данных:
    Строка текста.

Формат выходных данных:
    Строка текста без символов с индексами, кратными 3.

Примечание. Пример теста:
    "Python rocks!"
    -> "ytonroks"
"""

text = input()
result = ""

for i in range(len(text)):
    if i % 3 != 0:
        result += text[i]

print(result)