"""
Задача: «Второе вхождение» 2️⃣

На вход программе подаётся строка текста. Нужно вывести индекс второго
вхождения буквы "f". Если буква "f" встречается только один раз —
вывести "-1". Если не встречается ни разу — вывести "-2".

Формат входных данных:
    Строка текста.

Формат выходных данных:
    Индекс второго вхождения буквы "f", либо "-1", либо "-2" — по
    условию задачи.

Примечание. Пример теста:
    "offer"
    -> "2"
"""

text = input()
first = text.find("f")

if first == -1:
    print("-2")
else:
    second = text.find("f", first + 1)
    if second != -1:
        print(second)
    else:
        print("-1")