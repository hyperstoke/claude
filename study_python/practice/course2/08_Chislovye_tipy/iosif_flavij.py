"""
Задача: Иосиф Флавий

n человек, пронумерованных числами от 1 до n, стоят в кругу. Они начинают
считаться, каждый k-й по счёту человек выбывает из круга, после чего счёт
продолжается со следующего за ним человека. Определить номер человека,
который останется в кругу последним.

Вход:
два натуральных числа, каждое на отдельной строке: n — сколько человек
в кругу, k — какой по счёту выбывает.

Выход:
одно число — номер последнего оставшегося.

Примеры:
n = 7, k = 3   ->  4
n = 5, k = 2   ->  3
n = 10, k = 2  ->  5
n = 6, k = 1   ->  6   # k = 1: выбывают по порядку, последним остаётся n
n = 1, k = 1   ->  1   # один человек — он же и последний
n = 4, k = 7   ->  2   # k может быть больше n: счёт идёт по кругу не один раз
"""


wheel = list(range(1, int(input()) + 1))
kill = int(input())

start = 0
while len(wheel) > 1:
    i = (start + kill - 1) % len(wheel)
    del wheel[i]
    start = i

print(*wheel)
