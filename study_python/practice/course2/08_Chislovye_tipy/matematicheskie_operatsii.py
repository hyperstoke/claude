"""
Задача: математические операции над двумя целыми числами

На вход подаются два целых числа a и b (b != 0), каждое на отдельной строке.
Нужно вывести:
- сумму a и b;
- разность a и b;
- произведение a и b;
- частное a и b;
- целую часть от деления a на b;
- остаток от деления a на b;
- квадратный корень из суммы их 10-х степеней: sqrt(a**10 + b**10).

Вход:
две строки, в каждой одно целое число (вторая не равна нулю).
Выход:
семь результатов операций, каждый на отдельной строке, в порядке из условия.

Примеры:
"6", "2"  ->  "8", "4", "12", "3.0", "3", "0", "7776.065843342634"
# порядок вывода: сумма, разность, произведение, частное, //, %, корень
"""

from math import sqrt

a, b = int(input()), int(input())

print(a + b)
print(a - b)
print(a * b)
print(a / b)
print(a // b)
print(a % b)
print(sqrt(a ** 10 + b ** 10))
