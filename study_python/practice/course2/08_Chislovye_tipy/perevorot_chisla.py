"""
Задача: переворот числа

Дано пятизначное или шестизначное натуральное число. Развернуть в обратном
порядке его последние пять цифр (у шестизначного первая цифра остаётся на
месте). Вывести результат без незначащих нулей.

Вход:
одно натуральное число из 5 или 6 цифр.

Выход:
число после разворота, без ведущих нулей.

Примеры:
"12345"   ->  "54321"
"123456"  ->  "165432"   # первая цифра на месте, дальше 23456 -> 65432
"12300"   ->  "321"      # разворот даёт 00321, ведущие нули убираем
"100000"  ->  "100000"
"""

num = input()

if len(num) == 5:
    print(int(num[::-1]))

elif len(num) == 6:
    print(num[:1] + num[:0:-1])