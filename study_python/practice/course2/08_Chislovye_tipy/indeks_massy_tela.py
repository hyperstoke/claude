"""
Задача: индекс массы тела (ИМТ)

ИМТ = масса / (рост * рост), где масса в килограммах, рост в метрах.

Оценка:
- ИМТ от 18.5 до 25 включительно  -> "Оптимальная масса";
- ИМТ меньше 18.5                 -> "Недостаточная масса";
- ИМТ больше 25                   -> "Избыточная масса".

Вход:
две строки: масса и рост, оба числа читать как float.

Выход:
одна строка с оценкой массы по условию.

Примеры:
"60", "1.7"  ->  "Оптимальная масса"    # ИМТ ~ 20.76
"50", "1.8"  ->  "Недостаточная масса"  # ИМТ ~ 15.43
"90", "1.7"  ->  "Избыточная масса"     # ИМТ ~ 31.14
"""


def body_mass_index(mass: float, height: float) -> float:
    return mass / (height * height)


def bmi_assessment(bmi: float) -> str:
    if 18.5 <= bmi <= 25:
        return "Оптимальная масса"
    elif bmi < 18.5:
        return "Недостаточная масса"
    else:
        return "Избыточная масса"


m, h = float(input()), float(input())
print(bmi_assessment(body_mass_index(m, h)))