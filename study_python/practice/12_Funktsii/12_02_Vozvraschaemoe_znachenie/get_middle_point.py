"""
Задача: Середина отрезка

Напишите функцию get_middle_point(x1, y1, x2, y2), которая принимает
координаты концов отрезка (x1; y1) и (x2; y2) и ВОЗВРАЩАЕТ координаты
точки — середины этого отрезка.

Середина отрезка с концами (x1; y1) и (x2; y2):
((x1 + x2) / 2; (y1 + y2) / 2)

Вход: четыре числа-аргумента, приходят в функцию, input() не нужен
Выход: функция ничего не печатает, а возвращает две координаты середины

Пример вызова:
print(get_middle_point(0, 0, 10, 0))
print(get_middle_point(1, 5, 8, 3))

Вывод:
"5.0 0.0"
"4.5 4.0"
# в файле образец показан в кавычках; печатать кавычки не нужно
# два числа выводятся через пробел в одной строке
"""


def get_middle_point(x1, y1, x2, y2):
    return (x1 + x2) / 2, (y1 + y2) / 2


x1, y1, x2, y2 = [int(input()) for _ in range(4)]

a, b = get_middle_point(x1, y1, x2, y2)
print(a, b)