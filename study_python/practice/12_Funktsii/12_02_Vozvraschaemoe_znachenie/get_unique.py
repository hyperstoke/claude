"""
Задача: С каждого по одному 1️⃣

Напишите функцию get_unique(numbers), которая принимает список целых чисел
numbers и ВОЗВРАЩАЕТ новый список без повторяющихся значений, сохраняя
порядок появления чисел в исходном списке.

Вход: список-аргумент numbers — приходит в функцию
Выход: функция ничего не печатает, а возвращает новый список
Ввод в программе делается через eval(input()) — разбираться в eval() пока не нужно

Пример вызова:
print(get_unique([1, 2, 4, 3, 4]))
print(get_unique([0, -2, 1, -2, -3, 0]))
print(get_unique([5, 6, 7]))

Вывод:
"[1, 2, 4, 3]"
"[0, -2, 1, -3]"
"[5, 6, 7]"
# в файле образец показан в кавычках; печатать кавычки не нужно
# из [0, -2, 1, -2, -3, 0] остаётся первое вхождение каждого числа: 0 и -2 на своих местах
"""


def get_unique(numbers):
    new_numbers = []
    for i in range(len(numbers)):
        if numbers[i] not in new_numbers:
            new_numbers.append(numbers[i])
    return new_numbers


numbers = eval(input())


print(get_unique(numbers))
