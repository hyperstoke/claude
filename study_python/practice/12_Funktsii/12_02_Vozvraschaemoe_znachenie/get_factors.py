"""
Задача: Делители 1

Напишите функцию get_factors(num), которая принимает натуральное число num
и ВОЗВРАЩАЕТ список всех его делителей в порядке возрастания.

Вход: число-аргумент num — приходит в функцию, input() не нужен
Выход: функция ничего не печатает, а возвращает список

Пример вызова:
print(get_factors(1))
print(get_factors(5))
print(get_factors(10))

Вывод:
"[1]"
"[1, 5]"
"[1, 2, 5, 10]"
# в файле образец показан в кавычках; печатать кавычки не нужно
# делители 10 — это 1, 2, 5 и 10: само число тоже делитель
"""


def get_factors(num):
    divisors = []
    for i in range(1, num + 1):
        if num % i == 0:
            divisors.append(i)
    return len(divisors)


num = int(input())

print(get_factors(num))