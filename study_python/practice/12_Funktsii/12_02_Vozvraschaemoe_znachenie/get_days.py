"""
Задача: Количество дней в месяце

Напишите функцию get_days(month), которая принимает номер месяца (число
от 1 до 12) и ВОЗВРАЩАЕТ количество дней в этом месяце.
Год считается обычным, не високосным: в феврале 28 дней.

Вход: число-аргумент month — приходит в функцию, input() не нужен
Выход: функция ничего не печатает, а возвращает число (печатает вызывающий код)

Пример вызова:
print(get_days(1))
print(get_days(2))
print(get_days(9))

Вывод:
"31"
"28"
"30"
# в файле образец показан в кавычках; печатать кавычки не нужно
# 1 — январь, 2 — февраль, 9 — сентябрь
"""


def get_days(month):
    if month in [4, 6, 9, 11]:
        return 30
    elif month == 2:
        return 28
    else:
        return 31


num_month = int(input())

print(get_days(num_month))