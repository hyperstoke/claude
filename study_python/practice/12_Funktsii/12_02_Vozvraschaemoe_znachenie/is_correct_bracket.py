"""
Правильная скобочная последовательность

Напишите функцию is_correct_bracket(text), которая принимает в качестве
аргумента непустую строку text, состоящую из символов ( и ), и возвращает
значение True, если строка является правильной скобочной последовательностью,
или False в противном случае.

Примечание 1. Правильная скобочная последовательность — строка только из
символов ( и ), где каждой открывающей скобке найдётся парная закрывающая,
причём открывающая стоит левее своей закрывающей.

Примечание 2. Приведённый ниже код:
print(is_correct_bracket('()(()())'))
print(is_correct_bracket(')(())('))

должен выводить:
True     # каждая ( закрыта, порядок не нарушен
False    # первая скобка — закрывающая, закрывать нечего
"""


def is_correct_bracket(text: str) -> bool:
    opened = 0
    for ch in text:
        if ch == "(":
            opened += 1
        elif ch == ")":
            opened -= 1
            if opened < 0:
                return False
    return opened == 0


txt = input()


print(is_correct_bracket(txt))