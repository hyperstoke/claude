"""
Задача: Калькулятор доставки

Интернет-магазин делает экспресс-доставку: 1000 рублей за первый товар
и 120 рублей за каждый последующий. Напишите функцию
get_shipping_cost(quantity), которая принимает натуральное число quantity
(количество товаров в заказе) и ВОЗВРАЩАЕТ стоимость доставки.

Вход: одно число-аргумент quantity (>= 1), input() не нужен
Выход: функция ничего не печатает, а возвращает стоимость доставки

Пример вызова:
print(get_shipping_cost(1))
print(get_shipping_cost(3))

Вывод:
1000
1240
"""


def get_shipping_cost(quantity):
    return 1000 + 120 * (quantity - 1)


print(get_shipping_cost(int(input())))
