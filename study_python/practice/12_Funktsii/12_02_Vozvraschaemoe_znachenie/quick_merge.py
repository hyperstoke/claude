"""
Задача: Merge lists 2

На вход подаётся натуральное число n, а затем n строк с целыми числами
в порядке возрастания, разделёнными пробелом. Из строк формируются списки.
Напишите программу, которая объединяет все эти списки в один отсортированный
с помощью функции quick_merge(), а затем выводит его.

Вход: число n, затем n строк с числами по возрастанию через пробел
Выход: элементы итогового отсортированного списка через пробел

Пример входа:
"3"
"1 4 9"
"2 3 12"
"5 6 7"

Пример вывода:
"1 2 3 4 5 6 7 9 12"
# пример составлен по описанию форматов — блок «Тестовые данные» из условия
# не приложен, сверь с тем, что показывает Stepik
# списков теперь не два, а n штук: сколько именно — известно только в момент ввода
# вывод через пробел, а не списком: print([1, 2, 3]) выведет скобки и запятые

Имя функции задано условием — quick_merge. Какие у неё аргументы, условие
не уточняет; решай сам, но имя должно совпадать в точности.
"""


def quick_merge(values):
    merged_values = []
    for i in range(len(values)):
        merged_values += values[i]
    merged_values = list(map(int, merged_values))
    merged_values.sort()
    return merged_values


n = int(input())
values = [input().split() for _ in range(n)]


print(*quick_merge(values))