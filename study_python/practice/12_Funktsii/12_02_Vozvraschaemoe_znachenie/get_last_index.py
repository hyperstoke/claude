"""
Задача: Последнее вхождение 🔚

Напишите функцию get_last_index(data, value), которая принимает список data
и некоторое значение value, а ВОЗВРАЩАЕТ индекс последнего вхождения этого
значения в список — или текст ERROR! (без кавычек), если значения в списке нет.

Вход: два аргумента — список data и искомое значение value
Выход: функция ничего не печатает, а возвращает индекс (число) или строку "ERROR!"
Ввод в программе делается через eval(input()) — разбираться в eval() пока не нужно

Примечание: если значение встречается в списке ровно один раз, вернуть индекс
этого единственного вхождения.

Пример вызова:
print(get_last_index(['🦆', '🐝', '🐍', '🐍', '🐝'], '🐝'))
print(get_last_index(['Ross', 'Joey', 'Mike'], 'Ross'))
print(get_last_index(['синий', 'белый', 'фиолетовый'], 'красный'))

Вывод:
"4"
"0"
"ERROR!"
# в файле образец показан в кавычках; печатать кавычки не нужно
# '🐝' встречается на индексах 1 и 4 — нужен последний, 4
# 'Ross' встречается один раз, на индексе 0
"""


def get_last_index(data, value):
    last_index = None
    for i in range(len(data)):
        if data[i] == value:
            last_index = i
    if last_index is not None:
        return last_index
    else:
        return "ERROR!"


data = eval(input())
value = eval(input())


print(get_last_index(data, value))
