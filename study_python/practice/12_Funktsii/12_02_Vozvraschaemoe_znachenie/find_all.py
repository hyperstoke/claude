"""
Задача: Найти всех 👀

Строковый метод find('a') возвращает местоположение только ПЕРВОГО вхождения
символа в строке и ничего не знает про остальные.

Напишите функцию find_all(target, symbol), которая принимает строку target
и символ symbol, а ВОЗВРАЩАЕТ список со всеми местоположениями этого символа
в строке.

Вход: два аргумента — строка target и символ symbol
Выход: функция ничего не печатает, а возвращает список индексов
Примечание: если символ в строке не встречается, вернуть пустой список

Пример вызова:
print(find_all('abcdabcaaa', 'a'))
print(find_all('abcadbcaaa', 'e'))
print(find_all('abcadbcaaa', 'd'))

Вывод:
"[0, 4, 7, 8, 9]"
"[]"
"[4]"
# в файле образец показан в кавычках; печатать кавычки не нужно
# 'e' в строке нет — поэтому пустой список, а не сообщение об ошибке
# 'd' встречается один раз, на индексе 4 — список из одного элемента
"""


def find_all(target, symbol):
    return [i for i, char in enumerate(target) if char == symbol]


target = input()
symbol = input()


print(find_all(target, symbol))