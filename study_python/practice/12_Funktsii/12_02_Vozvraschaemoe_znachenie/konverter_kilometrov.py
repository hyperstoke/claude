"""
Задача: Конвертер километров

Напишите функцию convert_to_miles(km), которая принимает расстояние в
километрах и ВОЗВРАЩАЕТ расстояние в милях.

Формула: мили = километры * 0.6214

Вход: число-аргумент km — приходит в функцию, input() не нужен
Выход: функция ничего не печатает, а возвращает число (печатает вызывающий код)

Пример вызова:
print(convert_to_miles(1))
print(convert_to_miles(5))
print(convert_to_miles(10))

Вывод:
"0.6214"
"3.107"
"6.214"
# в файле образец показан в кавычках; печатать кавычки не нужно
"""


def convert_to_miles(km):
    mile = km * 0.6214
    return round(mile, 3)


num = int(input())

print(convert_to_miles(num))