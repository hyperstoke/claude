"""
Задача: Палиндром

Напишите функцию is_palindrome(text), которая принимает строку text
и ВОЗВРАЩАЕТ True, если текст является палиндромом, или False в противном случае.

Вход: один аргумент — строка text (в программе читается с клавиатуры)
Выход: функция ничего не печатает, а возвращает True или False

Примечание 1: палиндром — строка, которая читается одинаково в обоих направлениях.
Примечание 2: большие и маленькие буквы считать одинаковыми, а пробелы
и символы ,.!?- игнорировать.

Пример вызова:
print(is_palindrome('А роза упала на лапу Азора.'))
print(is_palindrome('Gabler Ruby - burrel bag!'))
print(is_palindrome('BEEGEEK'))
9
Вывод:
"True"
"True"
"False"
# в файле образец показан в кавычках; печатать кавычки не нужно
# после удаления пробелов, точки и приведения к одному регистру
# 'арозаупаланалапуазора' читается одинаково в обе стороны
"""


def is_palindrome(text):
    cleaned_text = "".join(s for s in text.lower() if s.isalpha())
    return cleaned_text == cleaned_text[::-1]


txt = input()


print(is_palindrome(txt))
