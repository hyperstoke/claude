"""
Задача: Магические даты

Магическая дата — это дата, когда день, умноженный на месяц, равен числу,
образованному последними двумя цифрами года.

Напишите функцию is_magic(date), которая принимает строковое представление
корректной даты (формат 'ДД.ММ.ГГГГ') и ВОЗВРАЩАЕТ True, если дата
магическая, иначе False.

Вход: один аргумент date — строка вида '10.06.1960', input() не нужен
Выход: функция ничего не печатает, а возвращает True или False

Пример вызова:
print(is_magic('10.06.1960'))   # 10 * 6 == 60  -> True
print(is_magic('11.06.1960'))   # 11 * 6 == 66  -> False

Вывод:
True
False

Тесты:
'10.06.1960' -> True
'15.03.1945' -> True     # 15 * 3 == 45
'03.11.2033' -> True     # 3 * 11 == 33
"""


def is_magic(date):
    day, month, year = date.split(".")
    return int(day) * int(month) == int(year[-2:])


date = input()


print(is_magic(date))
