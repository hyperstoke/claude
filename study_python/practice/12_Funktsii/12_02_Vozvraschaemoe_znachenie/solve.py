"""
Задача: Корни уравнения

Напишите функцию solve(a, b, c), которая принимает три целых числа
a, b, c — коэффициенты квадратного уравнения a*x**2 + b*x + c = 0 —
и ВОЗВРАЩАЕТ его корни в порядке возрастания.

Примечание 1: похожая задача уже была раньше.
Примечание 2: гарантируется, что уравнение имеет хотя бы один корень.

Вход: три числа-аргумента, приходят в функцию, input() не нужен
Выход: функция ничего не печатает, а возвращает два корня
       (если корень один, он возвращается дважды)

Пример вызова:
print(solve(1, -4, -5))
print(solve(-2, 7, -5))
print(solve(1, 2, 1))

Вывод:
"-1.0 5.0"
"1.0 2.5"
"-1.0 -1.0"
# в файле образец показан в кавычках; печатать кавычки не нужно
# два числа выводятся через пробел в одной строке, по возрастанию
"""
from math import sqrt


def solve(a, b, c):
    d = b ** 2 - 4 * a * c
    if d == 0:
        x = - b / (2 * a)
        return x, x
    else:
        x1 = - (b - sqrt(d)) / (2 * a)
        x2 = - (b + sqrt(d)) / (2 * a)
        return min(x1, x2), max(x1, x2)


a, b, c = int(input()), int(input()), int(input())

x1, x2 = solve(a, b, c)

print(x1, x2)
