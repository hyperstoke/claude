"""
Задача: Площадь и длина

Напишите функцию get_circle(radius), которая принимает радиус окружности
и ВОЗВРАЩАЕТ два значения: длину окружности и площадь круга, ограниченного
этой окружностью.

Формулы для радиуса r:
C = 2 * pi * r      # длина окружности
S = pi * r ** 2     # площадь круга

Для числа pi использовать глобальную константу из модуля math.

Вход: число radius — аргумент функции
Выход: функция ничего не печатает, а возвращает два числа —
сначала длину окружности, потом площадь круга

Пример вызова:
print(get_circle(1))
print(get_circle(1.5))

Вывод:
"6.283185307179586 3.141592653589793"
"9.42477796076938 7.0685834705770345"
# образец показан в кавычках; печатать кавычки не нужно
"""


from math import pi


# Функция возвращает длину и площадь круга
def get_circle(radius: float) -> tuple[float, float]:
    return 2 * pi * radius, pi * radius ** 2


num = float(input())

print(*get_circle(num))