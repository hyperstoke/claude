"""
Задача: Звёздный треугольник 2

Напишите функцию draw_triangle(fill, base), которая принимает два параметра:

fill — символ-заполнитель;
base — величина основания равнобедренного треугольника;

а затем выводит его.

Примечание: гарантируется, что основание треугольника — нечётное число.

Вход: два аргумента — символ fill и число base, приходят в функцию, input() не нужен
Выход: равнобедренный треугольник, лежащий на боку: основание — левая
вертикальная сторона из base символов (столько же строк), вершина смотрит вправо

Пример вызова:
draw_triangle("*", 9)

Вывод:
"*"
"**"
"***"
"****"
"*****"
"****"
"***"
"**"
"*"
# в файле образец показан в кавычках; печатать кавычки не нужно
# всего строк — base; длина растёт с 1 до base // 2 + 1 и симметрично убывает обратно
"""

def draw_triangle(fill, base):
    for i in range(1, base // 2 + 1):
        print(fill * i)
    for i in range(base // 2 + 1, 0, -1):
        print(fill * i)


fill, base = input(), int(input())


draw_triangle(fill, base)