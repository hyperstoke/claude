"""
Задача: В какое время созвон? 🌶️

Тимур живёт в Москве, а Антон — в Перми. Каждый раз, когда они договариваются
о времени созвона, Тимур говорит московское время, а Антону в уме приходится
переводить его на пермское. Но иногда Антон переводит время неправильно и
опаздывает на созвон, из-за чего Тимур сильно злится. Разница по времени между
Москвой и Пермью составляет 2 часа (в Перми на 2 часа больше).

Напишите функцию print_perm_time_call(msc_time), которая принимает на вход
строку — время созвона по московскому времени — в формате hh:mm — и выводит
время созвона по пермскому времени в следующем формате:

Созвон будет в HH:MM.

где HH:MM — время созвона по пермскому времени.

Примечание: гарантируется, что время созвона по московскому времени будет
не позднее 21:59.

Вход: строка-аргумент msc_time вида "hh:mm", приходит в функцию, input() не нужен
Выход: одна строка с пермским временем, с точкой в конце

Примеры вызова:
print_perm_time_call("14:30")
print_perm_time_call("07:05")

Вывод:
"Созвон будет в 16:30."
"Созвон будет в 09:05."
# в файле образец показан в кавычках; печатать кавычки не нужно
# час пишется двумя цифрами: 7 + 2 = 9, но в ответе "09", а не "9"

Расширение сверх условия (сделано по своей инициативе 2026-08-16; версия,
зачтённая Stepik, была с жёстким сдвигом +2 и одним параметром):
время может быть любым, а величина сдвига передаётся вторым параметром
и может быть отрицательной (пояса западнее: Калининград −1, Лиссабон −2).

Из-за этого появляется переход через полночь в обе стороны, и время
нормализуется по кругу остатком: (hour + hours_offset) % 24.

Примеры вызова:
print_call_time("23:30", 2)
print_call_time("09:15", -1)
print_call_time("01:00", -30)

Вывод:
"Созвон будет в 01:30."
"Созвон будет в 08:15."
"Созвон будет в 19:00."
# сдвиг больше суток тоже работает: остаток снимает любое число оборотов
"""


def print_call_time(base_time, hours_offset):
    hour, minute = map(int, base_time.split(":"))
    hour = (hour + hours_offset) % 24
    print(f"Созвон будет в {hour:02}:{minute:02}.")


base_time, hours_offset = input(), int(input())

print_call_time(base_time, hours_offset)
