"""
Задача: ФИО

Напишите функцию print_fio(name, surname, patronymic), которая принимает
три параметра:
name — имя человека;
surname — фамилия человека;
patronymic — отчество человека;
а затем выводит на печать ФИО человека.

Примечание: предусмотрите тот факт, что все три буквы в ФИО должны иметь
верхний регистр.

Вход: три строки-аргумента (имя, фамилия, отчество) — приходят в функцию,
input() не нужен
Выход: одна строка — фамилия, имя и отчество через пробел, каждое слово
с заглавной буквы

Пример вызова:
print_fio("иван", "иванов", "иванович")

Вывод:
"Иванов Иван Иванович"
# в файле образец показан в кавычках; печатать кавычки не нужно
# порядок слов — как в самой аббревиатуре ФИО: Фамилия, Имя, Отчество
"""


def print_fio(surname, name, patronymic):
    print((surname[0] + name[0] + patronymic[0]).upper())


name, surname, patronymic = input(), input(), input()
print_fio(surname, name, patronymic)