"""
Задача: Звёздный треугольник 1

Напишите функцию draw_triangle(), которая выводит звёздный прямоугольный
треугольник с катетами, равными 10, в соответствии с образцом.

Примечание: для вывода треугольника используйте цикл for.

Вход: ничего (функция без параметров)
Выход: 10 строк — в первой одна звёздочка, в каждой следующей на одну больше

Образец вывода:
"*"
"**"
"***"
"****"
"*****"
"******"
"*******"
"********"
"*********"
"**********"
# в файле образец показан в кавычках; печатать кавычки не нужно
"""


def draw_triangle():
    scale_triangle = 1
    for _ in range(10):
        print("*" * scale_triangle)
        scale_triangle += 1
        


draw_triangle()
