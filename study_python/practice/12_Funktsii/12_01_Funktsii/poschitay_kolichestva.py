"""
Задача: Посчитай количества 🌶️

Напишите функцию print_symbol_counts(s), которая принимает на вход слово s
и выводит для каждой буквы этого слова в лексикографическом порядке
в нижнем регистре на отдельной строке количество её вхождений в это слово
в следующем формате:

<L>: <N>

где <L> — некоторая буква слова s, <N> — количество вхождений этой буквы
в слово s.

Примечание: если в слове встречается одна и та же буква в разных регистрах,
то мы считаем это одной и той же буквой.

Вход: строка-аргумент s — слово, приходит в функцию, input() не нужен
Выход: по строке на каждую различную букву, буквы по алфавиту, в нижнем регистре

Примеры вызова:
print_symbol_counts("Hello")
print_symbol_counts("AaBb")

Вывод:
"e: 1"
"h: 1"
"l: 2"
"o: 1"
# в файле образец показан в кавычках; печатать кавычки не нужно
# каждая буква упоминается один раз, даже если встречается несколько

"a: 2"
"b: 2"
# «A» и «a» — одна и та же буква, их вхождения складываются
"""


def print_symbol_counts(word):
    word = word.lower()
    verified_letters = {}
    for letter in word:
        verified_letters[letter] = word.count(letter)

    for letter, count in sorted(verified_letters.items()):
        print(f"{letter}: {count}")


word = input()

print_symbol_counts(word)